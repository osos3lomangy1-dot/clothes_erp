records = []
seen = set()

def add(text, intent, slots=None, sector="all", kind="command"):
    text = re.sub(r"\s+", " ", text).strip()
    if not text or text in seen:
        return False
    seen.add(text)
    records.append({"text": text, "intent": intent, "slots": slots or {}, "sector": sector, "kind": kind})
    return True

def fill(intent, cores, target, kind="command", sector="all", p_prefix=0.55):
    """cores: list of str; generate variants until target new records."""
    n = 0
    tries = 0
    while n < target and tries < target * 40:
        tries += 1
        core = random.choice(cores)
        if add(wrap(core, p_prefix), intent, None, sector, kind):
            n += 1

