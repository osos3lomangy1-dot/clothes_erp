def wrap(core, p_prefix=0.55, p_suffix=0.3):
    pre = random.choice(PREFIX) if random.random() < p_prefix else ""
    suf = random.choice(SUFFIX) if random.random() < p_suffix else ""
    return " ".join(x for x in (pre, core, suf) if x).strip()

# ---------------------------------------------------------------- noise
def noise(t):
    ops = []
    ops.append(lambda s: s.replace("ة", "ه"))
    ops.append(lambda s: s.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا"))
    ops.append(lambda s: s.replace("ى", "ي"))
    ops.append(lambda s: s.replace("ذ", "ز"))
    ops.append(lambda s: s.replace("ض", "ظ"))
    ops.append(lambda s: re.sub(r"(.)", lambda m: m.group(1) * 2 if random.random() < 0.06 else m.group(1), s))
    def drop(s):
        w = s.split()
        if len(w) < 2:
            return s
        k = random.randrange(len(w))
        if len(w[k]) > 3:
            j = random.randrange(1, len(w[k]) - 1)
            w[k] = w[k][:j] + w[k][j + 1:]
        return " ".join(w)
    ops.append(drop)
    def swap(s):
        w = s.split()
        if len(w) < 2:
            return s
        k = random.randrange(len(w))
        if len(w[k]) > 3:
            j = random.randrange(0, len(w[k]) - 1)
            l = list(w[k]); l[j], l[j + 1] = l[j + 1], l[j]; w[k] = "".join(l)
        return " ".join(w)
    ops.append(swap)
    ops.append(lambda s: s.replace("ال", "ال ", 1) if random.random() < 0.0 else s)
    ops.append(lambda s: s.replace(" ", "  ") if random.random() < 0.3 else s)
    ops.append(lambda s: s + random.choice(["؟", "?", "!!", "..", " ؟؟"]))
    for f in random.sample(ops, k=random.choice([1, 1, 2, 2, 3])):
        t = f(t)
    return t.strip()

