def cnt_word(n):
    return SHORT[n] if n in SHORT and random.random() < 0.65 else (str(n) if random.random() < 0.5 else words(n))


def counted(n, unit):
    s1, s2, sp, sb = UNITS_[unit]
    if n == 1: return s1
    if n == 2: return s2
    if n <= 10: return (SHORT[n] if random.random() < 0.6 else str(n)) + " " + sp
    return (words(n) if random.random() < 0.5 else str(n)) + " " + sb


