FAMILIES = [("expr", fam_expr, 10), ("verbal", fam_verbal, 18), ("question", fam_question, 9), ("imperative", fam_imperative, 8),
            ("hortative", fam_hortative, 3), ("feeling", fam_feeling, 8), ("nominal", fam_nominal, 7), ("compound", fam_compound, 8),
            ("shop", fam_shop, 10), ("time", fam_time, 4), ("motion", fam_motion, 3), ("object", fam_object, 12)]
total_w = sum(w for _, _, w in FAMILIES)


def key(s):
    t = s.lower()
    t = re.sub("[\u064B-\u065F\u0640]", "", t)
    for a in "أإآٱ":
        t = t.replace(a, "ا")
    t = t.replace("ى", "ي").replace("ة", "ه")
    t = re.sub("[^\u0621-\u064A0-9a-z ]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def main():
    seen = set(); rows = []; fam_count = Counter()
    for name, fn, w in FAMILIES:
        quota = int(TARGET * 1.04 * w / total_w)
        got = 0; tries = 0
        while got < quota and tries < quota * 40:
            tries += 1
            try:
                s = fn()
            except Exception:
                continue
            s = re.sub(r"\s+", " ", s).replace(" ،", "،").replace(" ؟", "؟").strip()
            if len(s) < 2:
                continue
            kk = key(s)
            if not kk or kk in seen:
                continue
            seen.add(kk); rows.append((name, s)); got += 1
        fam_count[name] = got

    while len(rows) < TARGET:
        name, fn, _ = R(FAMILIES)
        s = re.sub(r"\s+", " ", fn()).replace(" ،", "،").replace(" ؟", "؟").strip()
        kk = key(s)
        if kk and kk not in seen:
            seen.add(kk); rows.append((name, s)); fam_count[name] += 1

    random.shuffle(rows)
    rows = rows[:TARGET]
    fam_final = Counter(n for n, _ in rows)
    with open(os.path.join(OUT, "egyptian_sentences_1m.txt"), "w", encoding="utf-8") as f:
        for _, s in rows:
            f.write(s + "\n")
    vocab = Counter()
    for _, s in rows:
        vocab.update(key(s).split())
    with open(os.path.join(OUT, "egyptian_vocab.tsv"), "w", encoding="utf-8") as f:
        for w_, c in vocab.most_common():
            f.write(f"{w_}\t{c}\n")
    with open(os.path.join(OUT, "egyptian_families.tsv"), "w", encoding="utf-8") as f:
        for n_, c in fam_final.most_common():
            f.write(f"{n_}\t{c}\n")
    print("sentences", len(rows), "| unique keys", len({key(s) for _, s in rows}), "| vocab", len(vocab))


if __name__ == "__main__":
    main()

