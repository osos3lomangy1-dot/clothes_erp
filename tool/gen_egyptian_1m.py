def assemble(opener, tm, tm_front, subj_txt, form, obj, place, comp, manner, tag):
    body = join(subj_txt, form, obj, place, comp, manner)
    if tm and tm_front:
        body = join(tm, body)
    elif tm:
        body = join(body, tm)
    return join(opener, body, tag)


