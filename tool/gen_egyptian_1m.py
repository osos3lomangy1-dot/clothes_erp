def pl3(w):
    return w[:-1] + "وا" if w.endswith("ي") else w + "وا"


def past(v, p):
    ps, p3 = v["ps"], v["p3"]
    return {"1s": ps + "ت", "2m": ps + "ت", "2f": ps + "تي", "3m": p3, "3f": v["p3f"] or p3 + "ت",
            "1p": ps + "نا", "2p": ps + "توا", "3p": pl3(p3)}[p]


def subj(v, p):
    st = v["st"]
    if p == "1s":
        return st if v["kind"] == "a" else "ا" + st
    pre = {"2m": "ت", "2f": "ت", "3m": "ي", "3f": "ت", "1p": "ن", "2p": "ت", "3p": "ي"}[p]
    if p == "2f":
        return pre + st if st.endswith("ي") else pre + st + "ي"
    if p in ("2p", "3p"):
        return pre + st[:-1] + "وا" if st.endswith("ي") else pre + st + "وا"
    return pre + st


def pres(v, p):
    return "ب" + (v["st"] if p == "1s" else subj(v, p))


def fut(v, p):
    return "ه" + (v["st"] if p == "1s" else subj(v, p))


def imp(v, p):
    i = v["imp"]
    if p == "2m":
        return i
    if p == "2f":
        return i if i.endswith("ي") else i + "ي"
    return i[:-1] + "وا" if i.endswith("ي") else i + "وا"


def neg_past(form):
    return "ما" + (form[1:] if form.startswith("ا") else form) + "ش"


def neg_subj(form):
    return "ما" + form + "ش"


