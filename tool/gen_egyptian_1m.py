def tense_form(v, p, tense):
    if tense == "pres": return pres(v, p), "pres"
    if tense == "fut": return fut(v, p), "fut"
    if tense == "past": return past(v, p), "past"
    if tense == "kan": return KAN[p] + " " + pres(v, p), "past"
    if tense == "neg_pres": return "مش " + pres(v, p), "pres"
    if tense == "neg_fut": return "مش " + fut(v, p), "fut"
    if tense == "neg_past": return neg_past(past(v, p)), "past"
    if tense == "neg_kan": return neg_past(KAN[p]) + " " + pres(v, p), "past"
    if tense == "lessa": return "لسه " + pres(v, p), "pres"
    if tense == "lessa_neg": return "لسه " + neg_past(past(v, p)), "past"
    if tense == "khalas": return "خلاص " + past(v, p), "past"
    if tense == "bardo": return "برضه " + pres(v, p), "pres"
    raise ValueError(tense)


